//! Spell checking and suggestions (reference: spell.c, spellfile.c,
//! spellsuggest.c).
//!
//! # Scope (M6)
//!
//! * plain-text word lists (one word per line, `#` comments, an optional
//!   `/encoding=utf-8` style header, optional `/flags` after the word) and Vim
//!   binary `.spl` files (version 50; the `LWORDTREE` is read);
//! * case-aware word checking plus the "SpellBad"/"SpellCap"/"SpellRare"
//!   groups the renderer uses for `bad_word_spans()`;
//! * `spellbadword()`, `spellsuggest()` and `soundfold()` support;
//! * in-memory good/bad/rare word lists for the `:spellgood` command family.
//!
//! # Not implemented (documented deviations)
//!
//! * `KWORDTREE`, `PREFIXTREE`, affix rules and compounding are ignored: only
//!   the base words literally stored in the `LWORDTREE` are known, so forms
//!   generated by affixes in a Vim `.spl` file (for example "houses" from
//!   "house") are reported bad unless the file also stores them;
//! * region (`WF_REGION`) filtering is ignored: every word is valid in every
//!   region, so [`WordStatus::Local`] is never returned by the checker;
//! * sound folding is a small approximation, not Vim's table-driven
//!   algorithm;
//! * `spellsuggest()` ranks candidates by (Damerau-)Levenshtein distance and
//!   then alphabetically instead of using Vim's phonetic/affix search;
//! * Vim defines `WF_RARE` as 0x08 and `WF_BANNED` as 0x10 in spell.h (the
//!   values found in real `.spl` files); those are the bits this reader uses.

use std::collections::HashSet;
use std::path::{Path, PathBuf};
use std::sync::{Mutex, MutexGuard};

use crate::Editor;

/// Vim spell file magic ("VIMspell").
const SPELL_MAGIC: &[u8] = b"VIMspell";
/// File format version written by Vim 8.2 (spellfile.c).
const VIMSPELL_VERSION: u8 = 50;

/// End-of-sections marker.
const SN_END: u8 = 255;

/// Highest "special" byte in a word tree (`BY_FLAGS2`).
const BY_SPECIAL: u8 = 3;
/// A shared child node follows (spellfile.c `BY_INDEX`).
const BY_INDEX: u8 = 1;
/// End of word with flags and flags2 bytes (`BY_FLAGS2`).
const BY_FLAGS2: u8 = 3;
/// Bit used while decoding the tree to mark a shared child: 0x08000000.
const SHARED_MASK: i32 = 0x0800_0000;

// Word flag bits (spell.h).
const WF_REGION: u32 = 0x01;
const WF_RARE: u32 = 0x08;
const WF_BANNED: u32 = 0x10;
const WF_AFX: u32 = 0x20;

/// Longest byte sequence accepted for one word while walking a tree. Vim's
/// MAXWLEN is 254 bytes; the margin only guards against malformed files whose
/// shared nodes form a cycle.
const MAX_WORD_BYTES: usize = 512;

/// Spelling state kept in [`Editor::spell`].
///
/// The cache is behind a [`Mutex`] so that read-only callers (the renderer
/// calling [`bad_word_spans`] with `&Editor`) can lazily load the word lists.
#[derive(Debug, Default)]
pub struct SpellState {
    inner: Mutex<SpellInner>,
}

/// One word read from a word list or a `.spl` file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct WordEntry {
    pub word: String,
    pub kind: WordKind,
}

/// The kind of a user supplied word.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WordKind {
    Good,
    Bad,
    Rare,
}

/// Result of checking one word.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WordStatus {
    /// The word is known (or correctly capitalized).
    Good,
    /// Not a known word, a banned word, or a mixed-case unknown word.
    Bad,
    /// Known but flagged as rare.
    Rare,
    /// A known word that must start with a capital.
    Cap,
    /// Known only for another region. The M6 reader ignores regions, so the
    /// checker never returns this variant; it exists for API compatibility.
    Local,
}

impl WordStatus {
    /// The string `spellbadword()` reports for this status ("" when good).
    pub fn as_str(self) -> &'static str {
        match self {
            WordStatus::Good => "",
            WordStatus::Bad => "bad",
            WordStatus::Rare => "rare",
            WordStatus::Cap => "caps",
            WordStatus::Local => "local",
        }
    }

    fn group(self) -> Option<&'static str> {
        match self {
            WordStatus::Good => None,
            WordStatus::Bad | WordStatus::Local => Some("SpellBad"),
            WordStatus::Rare => Some("SpellRare"),
            WordStatus::Cap => Some("SpellCap"),
        }
    }
}

/// Counts and file names reported by `:spellinfo`.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct SpellSummary {
    /// Number of known good words (loaded plus added).
    pub words: usize,
    /// Number of rare words.
    pub rare: usize,
    /// Number of banned/bad words.
    pub bad: usize,
    /// Number of words added with `:spellgood!`/`:spellwrong!`/`:spellrare!`.
    pub internal: usize,
    /// Word list files that were loaded.
    pub sources: Vec<String>,
    /// Files that could not be parsed (kept for `:spellinfo`).
    pub warnings: Vec<String>,
}

#[derive(Debug, Default)]
struct SpellInner {
    /// Cache key: 'spelllang' + 'spellfile' + 'runtimepath' at load time.
    key: Option<String>,
    /// Good/rare/banned words read from the word list files.
    words: HashSet<String>,
    rare: HashSet<String>,
    banned: HashSet<String>,
    /// Words added at run time without `!`, i.e. backed by 'spellfile'.
    added_good: HashSet<String>,
    added_bad: HashSet<String>,
    added_rare: HashSet<String>,
    /// Words added with `!` (Vim's internal word list).
    internal_good: HashSet<String>,
    internal_bad: HashSet<String>,
    internal_rare: HashSet<String>,
    sources: Vec<String>,
    warnings: Vec<String>,
}

impl SpellState {
    fn lock(&self) -> MutexGuard<'_, SpellInner> {
        // A panic while the cache is held should not disable spell checking for
        // the rest of the session.
        self.inner
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
    }

    /// Load the word lists for the current options if they changed.
    pub fn ensure_loaded(&self, ed: &Editor) {
        let key = cache_key(ed);
        let mut inner = self.lock();
        if inner.key.as_deref() == Some(key.as_str()) {
            return;
        }
        // The internal word list survives a 'spelllang' change; everything else
        // is re-read from disk.
        let internal_good = std::mem::take(&mut inner.internal_good);
        let internal_bad = std::mem::take(&mut inner.internal_bad);
        let internal_rare = std::mem::take(&mut inner.internal_rare);
        let mut fresh = SpellInner {
            key: Some(key),
            internal_good,
            internal_bad,
            internal_rare,
            ..SpellInner::default()
        };
        load_all(ed, &mut fresh);
        *inner = fresh;
    }

    /// Add a word to the in-memory list (used by the `:spell*` commands).
    pub fn add_word(&self, word: &str, kind: WordKind, internal: bool) {
        self.lock().add_word(word, kind, internal);
    }

    /// Remove a word from the in-memory lists (`:spellundo`).
    pub fn remove_word(&self, word: &str, internal: bool) {
        self.lock().remove_word(word, internal);
    }

    /// Counts and loaded file names for `:spellinfo`.
    pub fn summary(&self) -> SpellSummary {
        let inner = self.lock();
        let mut good: HashSet<&str> = HashSet::new();
        for set in [&inner.words, &inner.added_good, &inner.internal_good] {
            good.extend(set.iter().map(String::as_str));
        }
        let mut rare: HashSet<&str> = HashSet::new();
        for set in [&inner.rare, &inner.added_rare, &inner.internal_rare] {
            rare.extend(set.iter().map(String::as_str));
        }
        let mut bad: HashSet<&str> = HashSet::new();
        for set in [&inner.banned, &inner.added_bad, &inner.internal_bad] {
            bad.extend(set.iter().map(String::as_str));
        }
        SpellSummary {
            words: good.len(),
            rare: rare.len(),
            bad: bad.len(),
            internal: inner.internal_good.len()
                + inner.internal_rare.len()
                + inner.internal_bad.len(),
            sources: inner.sources.clone(),
            warnings: inner.warnings.clone(),
        }
    }

    /// A sorted sample of the known words, for `:spelldump`.
    pub fn sample_words(&self, limit: usize) -> Vec<String> {
        let inner = self.lock();
        let mut all: Vec<&str> = Vec::new();
        for set in [
            &inner.words,
            &inner.rare,
            &inner.added_good,
            &inner.internal_good,
            &inner.internal_rare,
        ] {
            all.extend(set.iter().map(String::as_str));
        }
        all.sort_unstable();
        all.dedup();
        all.truncate(limit);
        all.into_iter().map(str::to_string).collect()
    }

    /// Status of a single word (loads the word lists if needed).
    pub fn word_status(&self, ed: &Editor, word: &str) -> WordStatus {
        self.ensure_loaded(ed);
        self.lock().status(word, false)
    }

    /// The first badly spelled word in `text`, with its error type.
    ///
    /// This is the engine behind `spellbadword({str})`.
    pub fn first_bad_in(&self, ed: &Editor, text: &str) -> Option<(String, WordStatus)> {
        self.ensure_loaded(ed);
        let inner = self.lock();
        for token in scan_words(text) {
            let status = inner.status(&token.word, token.require_cap);
            if status != WordStatus::Good {
                return Some((token.word, status));
            }
        }
        None
    }

    /// The first badly spelled word at or after the cursor (which is left
    /// where it is; Vim moves it, RustVim's headless API does not need that).
    pub fn bad_word_at_cursor(&self, ed: &Editor) -> Option<(String, WordStatus)> {
        let line = ed.current_line();
        let col = ed.cursor().col;
        self.ensure_loaded(ed);
        let inner = self.lock();
        for token in scan_words(&line) {
            if token.end <= col {
                continue;
            }
            let status = inner.status(&token.word, token.require_cap);
            if status != WordStatus::Good {
                return Some((token.word, status));
            }
        }
        None
    }

    /// Spelling suggestions for `word`, ordered by edit distance and then
    /// alphabetically. `capital_only` keeps only words that start with a
    /// capital (Vim's third `spellsuggest()` argument).
    pub fn suggest(&self, ed: &Editor, word: &str, max: usize, capital_only: bool) -> Vec<String> {
        let word = word.trim();
        if word.is_empty() || max == 0 {
            return Vec::new();
        }
        self.ensure_loaded(ed);
        let inner = self.lock();
        let input_len = word.chars().count();
        let limit = if input_len <= 4 { 2 } else { 3 };
        let mut seen: HashSet<&str> = HashSet::new();
        let mut hits: Vec<(usize, &str)> = Vec::new();
        for set in [
            &inner.words,
            &inner.rare,
            &inner.added_good,
            &inner.added_rare,
            &inner.internal_good,
            &inner.internal_rare,
        ] {
            for candidate in set {
                if !seen.insert(candidate.as_str()) {
                    continue;
                }
                if candidate == word {
                    continue;
                }
                if candidate.chars().count().abs_diff(input_len) > limit {
                    continue;
                }
                let distance = edit_distance(word, candidate, limit);
                if distance <= limit {
                    hits.push((distance, candidate.as_str()));
                }
            }
        }
        hits.sort_by(|a, b| a.0.cmp(&b.0).then_with(|| a.1.cmp(b.1)));
        let mut out = Vec::new();
        for (_, candidate) in hits {
            if capital_only && !candidate.chars().next().is_some_and(|ch| ch.is_uppercase()) {
                continue;
            }
            out.push(candidate.to_string());
            if out.len() >= max {
                break;
            }
        }
        out
    }
}

impl SpellInner {
    fn exact(&self, word: &str) -> Option<WordStatus> {
        if self.added_bad.contains(word) || self.internal_bad.contains(word) {
            return Some(WordStatus::Bad);
        }
        if self.added_rare.contains(word) || self.internal_rare.contains(word) {
            return Some(WordStatus::Rare);
        }
        if self.added_good.contains(word) || self.internal_good.contains(word) {
            return Some(WordStatus::Good);
        }
        if self.banned.contains(word) {
            return Some(WordStatus::Bad);
        }
        if self.rare.contains(word) {
            return Some(WordStatus::Rare);
        }
        if self.words.contains(word) {
            return Some(WordStatus::Good);
        }
        None
    }

    /// Case-aware lookup (spell.c `spell_check`):
    ///
    /// * a capitalized word is accepted when its lowercase form is known;
    /// * an all-capital word is accepted when its lowercase form is known;
    /// * a lowercase word is a capitalization error when only the capitalized
    ///   form is known;
    /// * any other mix of cases must match exactly.
    fn status(&self, word: &str, require_cap: bool) -> WordStatus {
        let status = self.status_uncapped(word);
        if status == WordStatus::Good
            && require_cap
            && word
                .chars()
                .find(|ch| ch.is_alphabetic())
                .is_some_and(|ch| ch.is_lowercase())
        {
            return WordStatus::Cap;
        }
        status
    }

    fn status_uncapped(&self, word: &str) -> WordStatus {
        let word = word.trim();
        if word.is_empty() {
            return WordStatus::Good;
        }
        if let Some(status) = self.exact(word) {
            return status;
        }
        let lower = word.to_lowercase();
        if let Some(status) = self.derived(&lower) {
            return status;
        }
        match case_form(word) {
            CaseForm::Lower => {
                let capitalized = capitalize(&lower);
                if capitalized != word {
                    if let Some(status) = self.exact(&capitalized) {
                        return match status {
                            WordStatus::Good => WordStatus::Cap,
                            other => other,
                        };
                    }
                }
            }
            CaseForm::Capitalized | CaseForm::AllCaps => {
                if lower != word {
                    if let Some(status) = self.exact(&lower) {
                        return status;
                    }
                    let capitalized = capitalize(&lower);
                    if capitalized != word {
                        if let Some(status) = self.exact(&capitalized) {
                            return status;
                        }
                    }
                }
            }
            CaseForm::Mixed => {}
        }
        WordStatus::Bad
    }

    /// Accept common inflections when the base word is in the list.  The
    /// .spl affix tables are not parsed, so this covers the frequent English
    /// endings instead of reporting every inflection as misspelled.
    fn derived(&self, lower: &str) -> Option<WordStatus> {
        if lower.chars().count() < 4 {
            return None;
        }
        let mut stems: Vec<String> = Vec::new();
        let mut push = |stem: &str| {
            if stem.chars().count() >= 3 {
                stems.push(stem.to_string());
            }
        };
        if let Some(stem) = lower.strip_suffix("ies") {
            push(&format!("{stem}y"));
        }
        if let Some(stem) = lower.strip_suffix("es") {
            push(stem);
        }
        if let Some(stem) = lower.strip_suffix('s') {
            push(stem);
        }
        if let Some(stem) = lower.strip_suffix("ied") {
            push(&format!("{stem}y"));
        }
        if let Some(stem) = lower.strip_suffix("ed") {
            push(stem);
            push(&format!("{stem}e"));
        }
        if let Some(stem) = lower.strip_suffix("ing") {
            push(stem);
            push(&format!("{stem}e"));
            if stem.chars().count() >= 2 {
                let mut chars = stem.chars();
                let last = chars.next_back();
                let before = chars.next_back();
                if last == before {
                    if let Some(last) = last {
                        push(&stem[..stem.len() - last.len_utf8()]);
                    }
                }
            }
        }
        if let Some(stem) = lower.strip_suffix("est") {
            push(stem);
            push(&format!("{stem}e"));
            push(&format!("{stem}er"));
        }
        if let Some(stem) = lower.strip_suffix("er") {
            push(stem);
            push(&format!("{stem}e"));
        }
        if let Some(stem) = lower.strip_suffix("ly") {
            push(stem);
            push(&format!("{stem}le"));
        }
        for stem in stems {
            let capitalized = capitalize(&stem);
            for candidate in [stem, capitalized] {
                if let Some(status) = self.exact(&candidate) {
                    if status == WordStatus::Good {
                        return Some(WordStatus::Good);
                    }
                }
            }
        }
        None
    }

    fn add_word(&mut self, word: &str, kind: WordKind, internal: bool) {
        let word = word.trim();
        if word.is_empty() {
            return;
        }
        let (good, bad, rare) = if internal {
            (
                &mut self.internal_good,
                &mut self.internal_bad,
                &mut self.internal_rare,
            )
        } else {
            (
                &mut self.added_good,
                &mut self.added_bad,
                &mut self.added_rare,
            )
        };
        // The last command wins, like Vim commenting out the previous entry.
        good.remove(word);
        bad.remove(word);
        rare.remove(word);
        match kind {
            WordKind::Good => {
                good.insert(word.to_string());
            }
            WordKind::Bad => {
                bad.insert(word.to_string());
            }
            WordKind::Rare => {
                rare.insert(word.to_string());
            }
        }
    }

    fn remove_word(&mut self, word: &str, internal: bool) {
        let word = word.trim();
        if word.is_empty() {
            return;
        }
        if internal {
            self.internal_good.remove(word);
            self.internal_bad.remove(word);
            self.internal_rare.remove(word);
            return;
        }
        self.added_good.remove(word);
        self.added_bad.remove(word);
        self.added_rare.remove(word);
        // Also hide dictionary words, so `:spellgood x` followed by
        // `:spellundo x` makes `x` unknown again in this session.
        self.words.remove(word);
        self.rare.remove(word);
        self.banned.remove(word);
    }
}

/// True when 'spell' is enabled and the word is not known (a rare or
/// capitalization error also counts as "bad" for this helper).
pub fn is_bad_word(ed: &Editor, word: &str) -> bool {
    if !ed.options.bool_or("spell", false) {
        return false;
    }
    ed.spell.word_status(ed, word) != WordStatus::Good
}

/// Byte ranges of one line that the renderer should highlight as misspelled.
///
/// Returns `(start, end, group)` with group `"SpellBad"`, `"SpellCap"` or
/// `"SpellRare"`. Empty when 'spell' is off.
pub fn bad_word_spans(ed: &Editor, line: &str) -> Vec<(usize, usize, String)> {
    if !ed.options.bool_or("spell", false) {
        return Vec::new();
    }
    ed.spell.ensure_loaded(ed);
    let inner = ed.spell.lock();
    let mut spans = Vec::new();
    for token in scan_words(line) {
        let status = inner.status(&token.word, token.require_cap);
        if let Some(group) = status.group() {
            spans.push((token.start, token.end, group.to_string()));
        }
    }
    spans
}

/// Split `text` into words using the Vim spell word rules used by RustVim:
/// alphabetic characters, `_` and `-`, plus an apostrophe inside a word.
pub fn split_words(text: &str) -> Vec<(usize, usize, String)> {
    scan_words(text)
        .into_iter()
        .map(|token| (token.start, token.end, token.word))
        .collect()
}

/// Sound-fold a word (approximation of spellsuggest.c `soundfold()`):
/// lowercase, drop non-letters, map common sound-alike sequences and collapse
/// doubled letters.
pub fn soundfold(word: &str) -> String {
    let lower: Vec<char> = word
        .chars()
        .filter(|ch| ch.is_alphabetic())
        .flat_map(|ch| ch.to_lowercase())
        .collect();
    let mut out = String::with_capacity(lower.len());
    let mut last: Option<char> = None;
    let mut i = 0;
    while i < lower.len() {
        let ch = lower[i];
        let next = lower.get(i + 1).copied();
        let mapped: Option<&str> = match (ch, next) {
            ('p', Some('h')) => {
                i += 1;
                Some("f")
            }
            ('q', Some('u')) => {
                i += 1;
                Some("k")
            }
            ('x', _) => Some("ks"),
            ('z', _) => Some("s"),
            ('c', _) => Some("k"),
            _ => None,
        };
        match mapped {
            Some(text) => {
                for mapped_char in text.chars() {
                    if last != Some(mapped_char) {
                        out.push(mapped_char);
                        last = Some(mapped_char);
                    }
                }
            }
            None => {
                if last != Some(ch) {
                    out.push(ch);
                    last = Some(ch);
                }
            }
        }
        i += 1;
    }
    out
}

/// The entries of the 'spellfile' option (comma separated), with `~`
/// expanded.
pub fn spellfile_paths(ed: &Editor) -> Vec<PathBuf> {
    split_option_list(&ed.options.str_or("spellfile", ""))
        .into_iter()
        .map(|entry| expand_path(&entry))
        .collect()
}

/// Expand a leading `~/` (or `~\`) against `$HOME`/`%USERPROFILE%`.
pub fn expand_path(text: &str) -> PathBuf {
    let text = text.trim();
    if let Some(rest) = text.strip_prefix("~/").or_else(|| text.strip_prefix("~\\")) {
        if let Some(home) = std::env::var_os("HOME").or_else(|| std::env::var_os("USERPROFILE")) {
            return PathBuf::from(home).join(rest);
        }
    }
    PathBuf::from(text)
}

/// Read the words of a plain word list or a Vim `.spl` file.
pub fn read_words_from_file(path: &Path) -> Result<Vec<WordEntry>, String> {
    let data = std::fs::read(path).map_err(|err| err.to_string())?;
    if data.starts_with(SPELL_MAGIC) {
        parse_spl(&data)
    } else {
        Ok(parse_word_list(&String::from_utf8_lossy(&data)))
    }
}

/// Parse a plain-text word list.
///
/// Format (spellfile.c `spell_read_wordfile`): one word per line, `#` comments,
/// optional header lines such as `/encoding=utf-8`, and optional flags after a
/// slash. `/!` marks a banned word and `/?` a rare word; other flags are
/// accepted and ignored (they describe affixes, which M6 does not generate).
pub fn parse_word_list(text: &str) -> Vec<WordEntry> {
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let mut entries = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if is_word_list_header(line) {
            continue;
        }
        let token = line.split_whitespace().next().unwrap_or("");
        if token.is_empty() {
            continue;
        }
        let (word, flags) = match token.split_once('/') {
            Some((word, flags)) => (word, flags),
            None => (token, ""),
        };
        if word.is_empty() {
            continue;
        }
        let kind = if flags.starts_with('!') {
            WordKind::Bad
        } else if flags.starts_with('?') {
            WordKind::Rare
        } else {
            WordKind::Good
        };
        entries.push(WordEntry {
            word: word.to_string(),
            kind,
        });
    }
    entries
}

fn is_word_list_header(line: &str) -> bool {
    line.starts_with('/')
        && (line.contains('=')
            || line.starts_with("/rep")
            || line.starts_with("/sal")
            || line.starts_with("/sofo"))
}

/// Parse the `LWORDTREE` of a Vim spell file. `KWORDTREE`/`PREFIXTREE` and all
/// sections are skipped (spellfile.c `spell_read_tree`).
pub fn parse_spl(data: &[u8]) -> Result<Vec<WordEntry>, String> {
    if data.len() < 9 || !data.starts_with(SPELL_MAGIC) {
        return Err("not a Vim spell file".to_string());
    }
    let version = data[8];
    if version == 0 || version > VIMSPELL_VERSION {
        return Err(format!("unsupported spell file version {version}"));
    }
    let mut pos = 9usize;
    loop {
        let section = *data
            .get(pos)
            .ok_or_else(|| "truncated spell file (no section end)".to_string())?;
        pos += 1;
        if section == SN_END {
            break;
        }
        if pos + 5 > data.len() {
            return Err("truncated spell file section".to_string());
        }
        let len = u32::from_be_bytes([data[pos + 1], data[pos + 2], data[pos + 3], data[pos + 4]])
            as usize;
        pos += 5;
        if len > data.len().saturating_sub(pos) {
            return Err("truncated spell file section".to_string());
        }
        pos += len;
    }
    let tree = SpellTree::parse(data, &mut pos)?;
    let mut entries = Vec::new();
    if !tree.byts.is_empty() {
        collect_tree_words(&tree, &mut entries);
    }
    Ok(entries)
}

struct SpellTree {
    byts: Vec<u8>,
    idxs: Vec<i32>,
}

impl SpellTree {
    fn parse(data: &[u8], pos: &mut usize) -> Result<Self, String> {
        if *pos + 4 > data.len() {
            return Err("truncated word tree".to_string());
        }
        let nodecount =
            u32::from_be_bytes([data[*pos], data[*pos + 1], data[*pos + 2], data[*pos + 3]])
                as usize;
        *pos += 4;
        if nodecount == 0 {
            return Ok(SpellTree {
                byts: Vec::new(),
                idxs: Vec::new(),
            });
        }
        if nodecount > data.len() {
            return Err("invalid word tree size".to_string());
        }
        let mut byts = vec![0u8; nodecount];
        let mut idxs = vec![0i32; nodecount];
        read_tree_node(data, pos, &mut byts, &mut idxs, 0, 0)?;
        Ok(SpellTree { byts, idxs })
    }
}

fn read_tree_node(
    data: &[u8],
    pos: &mut usize,
    byts: &mut [u8],
    idxs: &mut [i32],
    startidx: usize,
    depth: usize,
) -> Result<usize, String> {
    if depth > MAX_WORD_BYTES || startidx >= byts.len() {
        return Err("invalid word tree node".to_string());
    }
    let maxidx = byts.len();
    let len_byte = read_u8(data, pos)?;
    if len_byte == 0 {
        return Err("invalid word tree node".to_string());
    }
    let len = len_byte as usize;
    if startidx + len >= maxidx {
        return Err("invalid word tree node".to_string());
    }
    let mut idx = startidx;
    byts[idx] = len_byte;
    idx += 1;
    for _ in 0..len {
        let mut byte = read_u8(data, pos)?;
        if byte <= BY_SPECIAL {
            if byte == 0 {
                idxs[idx] = 0;
            } else if byte == BY_INDEX {
                let nodeidx = read_u24(data, pos)?;
                if nodeidx >= maxidx {
                    return Err("invalid shared word tree node".to_string());
                }
                idxs[idx] = nodeidx as i32 | SHARED_MASK;
                byte = read_u8(data, pos)?;
            } else {
                let mut flags = u32::from(read_u8(data, pos)?);
                if byte == BY_FLAGS2 {
                    flags |= u32::from(read_u8(data, pos)?) << 8;
                }
                if flags & WF_REGION != 0 {
                    flags |= u32::from(read_u8(data, pos)?) << 16;
                }
                if flags & WF_AFX != 0 {
                    flags |= u32::from(read_u8(data, pos)?) << 24;
                }
                idxs[idx] = flags as i32;
                byte = 0;
            }
        }
        byts[idx] = byte;
        idx += 1;
    }
    for i in 1..=len {
        let node = startidx + i;
        if byts[node] != 0 {
            if idxs[node] & SHARED_MASK != 0 {
                idxs[node] &= !SHARED_MASK;
            } else {
                idxs[node] = idx as i32;
                idx = read_tree_node(data, pos, byts, idxs, idx, depth + 1)?;
            }
        }
    }
    Ok(idx)
}

fn collect_tree_words(tree: &SpellTree, out: &mut Vec<WordEntry>) {
    let mut bytes = Vec::with_capacity(32);
    walk_tree(tree, 0, &mut bytes, 0, out);
}

fn walk_tree(
    tree: &SpellTree,
    start: usize,
    bytes: &mut Vec<u8>,
    depth: usize,
    out: &mut Vec<WordEntry>,
) {
    if depth > MAX_WORD_BYTES || start >= tree.byts.len() {
        return;
    }
    let len = tree.byts[start] as usize;
    for i in 1..=len {
        let node = start + i;
        if node >= tree.byts.len() {
            return;
        }
        let byte = tree.byts[node];
        let link = tree.idxs[node];
        if byte == 0 {
            if bytes.is_empty() {
                continue;
            }
            if let Ok(word) = std::str::from_utf8(bytes) {
                let flags = (link as u32) & 0xFFFF;
                let kind = if flags & WF_BANNED != 0 {
                    WordKind::Bad
                } else if flags & WF_RARE != 0 {
                    WordKind::Rare
                } else {
                    WordKind::Good
                };
                out.push(WordEntry {
                    word: word.to_string(),
                    kind,
                });
            }
        } else {
            if link <= 0 {
                continue;
            }
            let child = link as usize;
            if child >= tree.byts.len() {
                continue;
            }
            bytes.push(byte);
            walk_tree(tree, child, bytes, depth + 1, out);
            bytes.pop();
        }
    }
}

fn read_u8(data: &[u8], pos: &mut usize) -> Result<u8, String> {
    let byte = *data
        .get(*pos)
        .ok_or_else(|| "truncated spell file".to_string())?;
    *pos += 1;
    Ok(byte)
}

fn read_u24(data: &[u8], pos: &mut usize) -> Result<usize, String> {
    if *pos + 3 > data.len() {
        return Err("truncated spell file".to_string());
    }
    let value = (usize::from(data[*pos]) << 16)
        | (usize::from(data[*pos + 1]) << 8)
        | usize::from(data[*pos + 2]);
    *pos += 3;
    Ok(value)
}

fn cache_key(ed: &Editor) -> String {
    format!(
        "{}\u{1}{}\u{1}{}",
        ed.options.str_or("spelllang", ""),
        ed.options.str_or("spellfile", ""),
        ed.options.str_or("runtimepath", "")
    )
}

fn split_option_list(value: &str) -> Vec<String> {
    value
        .split(',')
        .map(str::trim)
        .filter(|item| !item.is_empty())
        .map(str::to_string)
        .collect()
}

fn load_all(ed: &Editor, inner: &mut SpellInner) {
    let mut seen: HashSet<PathBuf> = HashSet::new();
    let languages = split_option_list(&ed.options.str_or("spelllang", ""));
    let runtimepath = split_option_list(&ed.options.str_or("runtimepath", ""));
    for language in &languages {
        'language: for file_name in language_file_names(language) {
            for dir in &runtimepath {
                let path = Path::new(dir).join("spell").join(&file_name);
                if path.is_file() {
                    if seen.insert(path.clone()) {
                        load_one(&path, inner);
                    }
                    break 'language;
                }
            }
        }
    }
    for entry in split_option_list(&ed.options.str_or("spellfile", "")) {
        let path = expand_path(&entry);
        let resolved = if path.is_file() {
            Some(path)
        } else {
            let compiled = PathBuf::from(format!("{}.spl", path.display()));
            compiled.is_file().then_some(compiled)
        };
        if let Some(path) = resolved {
            if seen.insert(path.clone()) {
                load_one(&path, inner);
            }
        }
    }
}

fn language_file_names(language: &str) -> Vec<String> {
    let mut bases = vec![language.to_string()];
    if let Some((base, _region)) = language.split_once('_') {
        if base != language {
            bases.push(base.to_string());
        }
    }
    let mut names = Vec::new();
    for base in &bases {
        for suffix in [".utf-8.spl", ".ascii.spl", ".latin1.spl", ".txt", ".dic"] {
            names.push(format!("{base}{suffix}"));
        }
    }
    names
}

fn load_one(path: &Path, inner: &mut SpellInner) {
    match read_words_from_file(path) {
        Ok(entries) => {
            let count = entries.len();
            for entry in entries {
                match entry.kind {
                    WordKind::Good => {
                        inner.words.insert(entry.word);
                    }
                    WordKind::Bad => {
                        inner.banned.insert(entry.word);
                    }
                    WordKind::Rare => {
                        inner.rare.insert(entry.word);
                    }
                }
            }
            inner
                .sources
                .push(format!("{} ({count} words)", path.display()));
        }
        Err(err) => inner.warnings.push(format!("{}: {err}", path.display())),
    }
}

struct WordToken {
    start: usize,
    end: usize,
    word: String,
    require_cap: bool,
}

fn scan_words(text: &str) -> Vec<WordToken> {
    let chars: Vec<(usize, char)> = text.char_indices().collect();
    let mut tokens = Vec::new();
    let mut previous_end: Option<usize> = None;
    let mut i = 0;
    while i < chars.len() {
        let (start, ch) = chars[i];
        if !(ch.is_alphabetic() || ch == '_') {
            i += 1;
            continue;
        }
        let mut j = i;
        while j < chars.len() {
            let current = chars[j].1;
            if current.is_alphabetic() || current == '_' {
                j += 1;
            } else if current == '-' || current == '\'' || current == '\u{2019}' {
                let next_is_word = chars
                    .get(j + 1)
                    .is_some_and(|(_, next)| next.is_alphabetic() || *next == '_');
                if next_is_word {
                    j += 1;
                } else {
                    break;
                }
            } else {
                break;
            }
        }
        let end = chars.get(j).map_or(text.len(), |(byte, _)| *byte);
        let word = &text[start..end];
        if word.chars().any(char::is_alphabetic) {
            let require_cap =
                previous_end.is_some_and(|prev| gap_ends_sentence(&text[prev..start]));
            tokens.push(WordToken {
                start,
                end,
                word: word.to_string(),
                require_cap,
            });
            previous_end = Some(end);
        }
        i = j;
    }
    tokens
}

/// True when the gap between two words ends a sentence (approximates the
/// default 'spellcapcheck' `[.?!]\s*["')\]]*\s*$`).
fn gap_ends_sentence(gap: &str) -> bool {
    let trimmed = gap.trim_end_matches(char::is_whitespace);
    let trimmed = trimmed.trim_end_matches(['"', '\'', ')', ']', '}']);
    let trimmed = trimmed.trim_end_matches(char::is_whitespace);
    trimmed.ends_with('.') || trimmed.ends_with('!') || trimmed.ends_with('?')
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum CaseForm {
    Lower,
    Capitalized,
    AllCaps,
    Mixed,
}

fn case_form(word: &str) -> CaseForm {
    let letters: Vec<char> = word.chars().filter(|ch| ch.is_alphabetic()).collect();
    if letters.is_empty() {
        return CaseForm::Mixed;
    }
    if letters.iter().all(|ch| ch.is_uppercase()) {
        return CaseForm::AllCaps;
    }
    if letters.iter().all(|ch| ch.is_lowercase()) {
        return CaseForm::Lower;
    }
    if letters[0].is_uppercase() && letters[1..].iter().all(|ch| ch.is_lowercase()) {
        CaseForm::Capitalized
    } else {
        CaseForm::Mixed
    }
}

fn capitalize(lower: &str) -> String {
    let mut chars = lower.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
        None => String::new(),
    }
}

fn edit_distance(a: &str, b: &str, limit: usize) -> usize {
    if a.is_ascii() && b.is_ascii() {
        distance_generic(a.as_bytes(), b.as_bytes(), limit)
    } else {
        let a: Vec<char> = a.chars().collect();
        let b: Vec<char> = b.chars().collect();
        distance_generic(&a, &b, limit)
    }
}

/// Damerau-Levenshtein (optimal string alignment) distance, giving up (and
/// returning `limit + 1`) once a whole row exceeds `limit`.
fn distance_generic<T: PartialEq>(a: &[T], b: &[T], limit: usize) -> usize {
    let (a, b) = if a.len() <= b.len() { (a, b) } else { (b, a) };
    if b.len() - a.len() > limit {
        return limit + 1;
    }
    let width = b.len();
    // Three full-size rows rotated by the swaps below: two_rows_back holds
    // row i-2, previous row i-1 and current is the scratch row being filled.
    let mut two_rows_back = vec![0usize; width + 1];
    let mut previous: Vec<usize> = (0..=width).collect();
    let mut current = vec![0usize; width + 1];
    for i in 1..=a.len() {
        current[0] = i;
        let mut row_min = i;
        for j in 1..=width {
            let cost = usize::from(a[i - 1] != b[j - 1]);
            let mut value = (previous[j] + 1)
                .min(current[j - 1] + 1)
                .min(previous[j - 1] + cost);
            if i >= 2 && j >= 2 && a[i - 1] == b[j - 2] && a[i - 2] == b[j - 1] {
                value = value.min(two_rows_back[j - 2] + 1);
            }
            current[j] = value;
            row_min = row_min.min(value);
        }
        if row_min > limit {
            return limit + 1;
        }
        std::mem::swap(&mut two_rows_back, &mut previous);
        std::mem::swap(&mut previous, &mut current);
    }
    previous[width]
}
