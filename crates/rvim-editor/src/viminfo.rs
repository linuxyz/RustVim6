//! viminfo file: read and write (reference: viminfo.c, history.c).
//!
//! Vim keeps a small amount of state between sessions in a line-oriented
//! "viminfo" file: file marks, register contents, the last search pattern,
//! command and search history, the buffer list, the global variables and the
//! current directory.  [VimInfo] models that state, [VimInfo::format] renders it
//! and [VimInfo::parse] reads it back.
//!
//! # Layout
//!
//! The file is a sequence of comment lines (starting with '#') and
//! single-character "section marker" lines.  Markers are dispatched exactly like
//! Vim's read_viminfo_up_to_marks(): the first byte of a line selects the
//! parser, so an unknown marker (or a malformed line) is simply skipped.  Empty
//! lines separate sections.
//!
//! | marker | section             | line format                                    |
//! |--------|---------------------|------------------------------------------------|
//! | '%'    | buffer list         | %[index]name (index marks the current buffer)  |
//! | '\''   | file marks          | '{name} TAB {lnum} TAB {col} TAB {file}        |
//! | '@'    | registers           | @{name} TAB {flag} TAB {n} TAB {line} ...      |
//! | '/'    | search history      | /{n} TAB {pattern}                             |
//! | ':'    | command history     | :{n} TAB {command}                             |
//! | '!'    | global variables    | !{name} TAB {value}                            |
//! | '~'    | last search pattern | ~/{pattern}; ~c{cwd} stores our directory      |
//! | '#'    | comment             | ignored                                        |
//! | '*'    | 'encoding' line     | ignored (*utf-8 is written)                    |
//!
//! The header mirrors write_viminfo() (viminfo.c:2945-2950) and the
//! "# File marks:" / "# Buffer list:" comments mirror write_viminfo_marks() and
//! write_viminfo_bufferlist().
//!
//! # Escaping
//!
//! Every string that must fit on one line is escaped with backslash escapes:
//! a doubled backslash, \\n, \\r and \\t for newline, carriage return and tab,
//! and \\xNN for the remaining control characters.  Reading also accepts Vim's
//! historical CTRL-V escapes (CTRL-V n for newline, CTRL-V CTRL-V for CTRL-V) so
//! simple files written by real Vim still parse.
//!
//! # Deliberate deviations from Vim 8.2
//!
//! * Everything is UTF-8; the encoding line is written as *utf-8 instead of
//!   *encoding=utf-8 and no iconv conversion is attempted.
//! * Vim escapes strings with CTRL-V; we use backslash escapes (a newline in a
//!   buffer name is written as \\n, as specified for this module).  A real Vim
//!   file containing backslashes that happen to form escape sequences may
//!   therefore be decoded differently.
//! * The buffer list stores a plain name.  Vim's native "%name TAB lnum TAB col"
//!   line is still accepted (the position is discarded), but the index we write
//!   is a 1-based index into buffers.  Consequently a stored name that starts
//!   with a decimal digit would be read back as an index; editors should store
//!   absolute paths.
//! * Registers are stored on one line: @{name} TAB {flag} TAB {n} TAB {line} ...
//!   with a double quote as flag for a linewise register and an empty flag field
//!   for a charwise one.  {n} counts the TAB-separated segments, so any text
//!   (including a trailing newline) round-trips exactly.  Vim's native
//!   multi-line block ("a TAB LINE TAB 0" followed by TAB-prefixed lines) is
//!   also accepted when reading.
//! * History entries are written in list order; the {n} number is cosmetic (it
//!   is written descending because the list is "newest to oldest").
//! * Marks are a flat list that carries the file name, like Vim's file marks,
//!   not the per-buffer "> file" blocks.  lnum is 1-based and col is 0-based,
//!   matching pos_T.
//! * Global variables are plain strings (there is no type tag) and everything
//!   else Vim stores -- timestamps, the bar-line ('|') sections, the substitute
//!   pattern, the jumplist, 'viminfo' size limits and the merge-with-old-file
//!   logic -- is out of scope for this module.

use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use rvim_core::{VimError, VimResult};

/// Error code for viminfo I/O failures (Vim's E484).
const E_VIMINFO_IO: &str = "E484";

/// The fixed prologue; real Vim writes the same three comments and an encoding
/// line in write_viminfo().
const HEADER: &str = concat!(
    "# This viminfo file was generated by Vim 8.2.\n",
    "# You may edit it if you're careful!\n",
    "\n",
    "# Value of 'encoding' when this file was written\n",
    "*utf-8\n",
    "\n",
);

/// The state stored in one viminfo file.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct VimInfo {
    /// File marks, in file order.
    pub marks: Vec<VimInfoMark>,
    /// Non-empty registers.
    pub registers: Vec<VimInfoRegister>,
    /// Last search pattern (~/{pattern}).
    pub last_search: Option<String>,
    /// Command-line history, index 0 is the newest entry.
    pub cmd_history: Vec<String>,
    /// Search-string history, index 0 is the newest entry.
    pub search_history: Vec<String>,
    /// Buffer-list names, in the order they were written.
    pub buffers: Vec<String>,
    /// 1-based index into buffers of the current buffer.
    pub cur_buf: Option<usize>,
    /// Current working directory (not saved by real Vim).
    pub cwd: Option<String>,
    /// Global variables whose name starts with an uppercase letter.
    pub globals: Vec<(String, String)>,
}

/// One file mark: lnum is 1-based, col is 0-based.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct VimInfoMark {
    pub name: char,
    pub file: String,
    pub lnum: i64,
    pub col: i64,
}

/// One register: linewise distinguishes "a (linewise) from "ap (charwise).  A
/// linewise register's text normally ends with a newline.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct VimInfoRegister {
    pub name: char,
    pub text: String,
    pub linewise: bool,
}

impl VimInfo {
    /// Read and parse path.  A missing file is not an error: it yields
    /// Ok(VimInfo::default()), mirroring Vim's "no viminfo file yet" case.  Any
    /// other I/O failure returns an E484-style [VimError].
    pub fn read(path: &Path) -> VimResult<VimInfo> {
        match fs::read(path) {
            Ok(bytes) => {
                let text = String::from_utf8_lossy(&bytes);
                let text = text.strip_prefix('\u{feff}').unwrap_or(&text);
                Ok(Self::parse(text))
            }
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => Ok(VimInfo::default()),
            Err(err) => Err(VimError::new(
                E_VIMINFO_IO,
                format!("Can't read viminfo file \"{}\": {err}", path.display()),
            )),
        }
    }

    /// Write the file atomically: the text goes to a temporary file next to
    /// path which is renamed over the real file only after a successful flush,
    /// so an interrupted write never leaves a truncated viminfo.
    pub fn write(&self, path: &Path) -> VimResult<()> {
        let text = self.format();
        let tmp = temp_path(path);
        let result = fs::File::create(&tmp).and_then(|mut file| {
            file.write_all(text.as_bytes())?;
            file.sync_all()?;
            drop(file);
            fs::rename(&tmp, path)
        });
        if let Err(err) = result {
            // Best effort: do not leave the temporary file behind.
            let _ = fs::remove_file(&tmp);
            return Err(VimError::new(
                E_VIMINFO_IO,
                format!("Can't write viminfo file \"{}\": {err}", path.display()),
            ));
        }
        Ok(())
    }

    /// Parse a viminfo file.  Total: unknown sections and malformed lines are
    /// skipped and no input can make it panic.
    pub fn parse(text: &str) -> VimInfo {
        let mut vi = VimInfo::default();
        // Content of a register written in Vim's native multi-line block form,
        // collected until the first line that does not start with a TAB.
        let mut pending: Option<(char, bool, Vec<String>)> = None;

        for raw in text.split('\n') {
            let line = raw.strip_suffix('\r').unwrap_or(raw);
            if line.is_empty() {
                if let Some(block) = pending.take() {
                    push_register_block(&mut vi, block);
                }
                continue;
            }
            if let Some(rest) = line.strip_prefix('\t') {
                // Continuation line of a native register block; ignored when
                // it belongs to a section this module does not understand.
                if let Some((_, _, lines)) = pending.as_mut() {
                    lines.push(unescape_str(rest));
                }
                continue;
            }
            if let Some(block) = pending.take() {
                push_register_block(&mut vi, block);
            }
            let Some((marker, rest)) = split_first(line) else {
                continue;
            };
            match marker {
                '#' | '*' | '|' => {}
                '%' => {
                    let (index, name) = parse_buffer(rest);
                    if name.is_empty() {
                        continue;
                    }
                    if index.is_some() {
                        vi.cur_buf = index;
                    }
                    vi.buffers.push(name);
                }
                '\'' => {
                    if let Some(mark) = parse_mark(rest) {
                        vi.marks.push(mark);
                    }
                }
                '@' => {
                    if let Some(register) = parse_register(rest) {
                        vi.registers.push(register);
                    }
                }
                '"' => {
                    if let Some((name, linewise)) = parse_native_register_start(rest) {
                        pending = Some((name, linewise, Vec::new()));
                    }
                }
                ':' => {
                    let (numbered, value) = split_history_number(rest);
                    if numbered || !value.is_empty() {
                        vi.cmd_history.push(unescape_str(value));
                    }
                }
                '/' => {
                    let (numbered, value) = split_history_number(rest);
                    let value = if numbered {
                        value
                    } else {
                        // Vim's native search-history line is "/<sep><pattern>".
                        value.strip_prefix(' ').unwrap_or(value)
                    };
                    if numbered || !value.is_empty() {
                        vi.search_history.push(unescape_str(value));
                    }
                }
                '!' => {
                    if let Some(entry) = parse_global(rest) {
                        vi.globals.push(entry);
                    }
                }
                '~' => {
                    if let Some(cwd) = rest.strip_prefix('c') {
                        vi.cwd = Some(unescape_str(cwd));
                    } else if vi.last_search.is_none() {
                        if let Some(pattern) = parse_last_search(rest) {
                            vi.last_search = Some(pattern);
                        }
                    }
                }
                _ => {}
            }
        }
        if let Some(block) = pending {
            push_register_block(&mut vi, block);
        }
        vi
    }

    /// Render the file.  The result always ends with a blank line.
    pub fn format(&self) -> String {
        let mut out = String::from(HEADER);

        out.push_str("# Last Search Pattern:\n");
        if let Some(pattern) = &self.last_search {
            out.push_str("~/");
            out.push_str(&escape_str(pattern));
            out.push('\n');
        }

        out.push_str("\n# Command Line History (newest to oldest):\n");
        let count = self.cmd_history.len();
        for (idx, command) in self.cmd_history.iter().enumerate() {
            out.push(':');
            out.push_str(&(count - idx).to_string());
            out.push('\t');
            out.push_str(&escape_str(command));
            out.push('\n');
        }

        out.push_str("\n# Search String History (newest to oldest):\n");
        let count = self.search_history.len();
        for (idx, pattern) in self.search_history.iter().enumerate() {
            out.push('/');
            out.push_str(&(count - idx).to_string());
            out.push('\t');
            out.push_str(&escape_str(pattern));
            out.push('\n');
        }

        out.push_str("\n# Registers:\n");
        for register in &self.registers {
            out.push('@');
            out.push(register.name);
            out.push('\t');
            if register.linewise {
                out.push('"');
            }
            out.push('\t');
            // One TAB-separated segment per line of text, plus a final empty
            // segment when the text ends with a newline; joining the segments
            // with newlines reproduces the text exactly.
            let segments: Vec<&str> = register.text.split('\n').collect();
            out.push_str(&segments.len().to_string());
            for segment in segments {
                out.push('\t');
                out.push_str(&escape_str(segment));
            }
            out.push('\n');
        }

        out.push_str("\n# global variables:\n");
        for (name, value) in &self.globals {
            out.push('!');
            out.push_str(&escape_str(name));
            out.push('\t');
            out.push_str(&escape_str(value));
            out.push('\n');
        }

        out.push_str("\n# Current working directory:\n");
        if let Some(cwd) = &self.cwd {
            out.push_str("~c");
            out.push_str(&escape_str(cwd));
            out.push('\n');
        }

        out.push_str("\n# File marks:\n");
        for mark in &self.marks {
            out.push('\'');
            out.push(mark.name);
            out.push('\t');
            out.push_str(&mark.lnum.to_string());
            out.push('\t');
            out.push_str(&mark.col.to_string());
            out.push('\t');
            out.push_str(&escape_str(&mark.file));
            out.push('\n');
        }

        out.push_str("\n# Buffer list:\n");
        out.push_str("# (the current buffer is marked with its 1-based index after '%')\n");
        for (idx, name) in self.buffers.iter().enumerate() {
            out.push('%');
            let number = idx + 1;
            if self.cur_buf == Some(number) {
                out.push_str(&number.to_string());
            }
            out.push_str(&escape_str(name));
            out.push('\n');
        }

        out.push('\n');
        out
    }
}

/// Split the first character off s without ever slicing inside a UTF-8 sequence
/// (all other parsers may slice at ASCII offsets found by find()).
fn split_first(s: &str) -> Option<(char, &str)> {
    let mut chars = s.chars();
    let first = chars.next()?;
    Some((first, chars.as_str()))
}

/// {n} TAB value -> (true, value); anything else is returned unchanged so
/// old-style lines without a number still parse.
fn split_history_number(rest: &str) -> (bool, &str) {
    if let Some((number, value)) = rest.split_once('\t') {
        if !number.is_empty() && number.bytes().all(|byte| byte.is_ascii_digit()) {
            return (true, value);
        }
    }
    (false, rest)
}

/// Parse the part of a '%' line after the marker.  Returns the 1-based
/// current-buffer index when the line starts with one, and the buffer name.
fn parse_buffer(rest: &str) -> (Option<usize>, String) {
    // Vim's native form is "<name> TAB <lnum> TAB <col>"; the position is not
    // modelled here, so only the name survives.
    if let Some((name, _position)) = rest.split_once('\t') {
        return (None, unescape_str(name));
    }
    let digits = rest.bytes().take_while(u8::is_ascii_digit).count();
    if digits > 0 && digits < rest.len() {
        if let Ok(index) = rest[..digits].parse::<usize>() {
            return (Some(index), unescape_str(&rest[digits..]));
        }
    }
    (None, unescape_str(rest))
}

/// Parse '{name} TAB {lnum} TAB {col} TAB {file}' (and Vim's whitespace
/// separated '{name}  {lnum}  {col}  {file}').
fn parse_mark(rest: &str) -> Option<VimInfoMark> {
    let (name, rest) = split_first(rest)?;
    if let Some(rest) = rest.strip_prefix('\t') {
        let mut fields = rest.splitn(3, '\t');
        let lnum = fields.next()?.trim().parse::<i64>().ok()?;
        let col = fields.next()?.trim().parse::<i64>().ok()?;
        let file = fields.next().unwrap_or("");
        return Some(VimInfoMark {
            name,
            file: unescape_str(file),
            lnum,
            col,
        });
    }
    let rest = rest.trim_start();
    let (lnum, rest) = take_int(rest)?;
    let (col, rest) = take_int(rest.trim_start())?;
    Some(VimInfoMark {
        name,
        file: unescape_str(rest.trim_start()),
        lnum,
        col,
    })
}

/// Parse an optionally signed decimal at the start of s.
fn take_int(s: &str) -> Option<(i64, &str)> {
    let bytes = s.as_bytes();
    let mut end = 0;
    if end < bytes.len() && (bytes[end] == b'-' || bytes[end] == b'+') {
        end += 1;
    }
    let digits_start = end;
    while end < bytes.len() && bytes[end].is_ascii_digit() {
        end += 1;
    }
    if end == digits_start {
        return None;
    }
    Some((s[..end].parse().ok()?, &s[end..]))
}

/// Parse the part of an '@' line after the marker.
fn parse_register(rest: &str) -> Option<VimInfoRegister> {
    let (name, rest) = split_first(rest)?;
    // Real Vim appends '@' to the name when the register was used for @@.
    let rest = rest.strip_prefix('@').unwrap_or(rest);
    let rest = rest.strip_prefix('\t')?;
    let (flag, rest) = rest.split_once('\t').unwrap_or((rest, ""));
    let linewise = flag_is_linewise(flag);
    let text = match rest.split_once('\t') {
        Some((_count, body)) => body
            .split('\t')
            .map(unescape_str)
            .collect::<Vec<_>>()
            .join("\n"),
        None => String::new(),
    };
    Some(VimInfoRegister {
        name,
        text,
        linewise,
    })
}

/// A register flag is either our '"' (linewise) / empty (charwise) marker or
/// Vim's LINE / CHAR / BLOCK type name.
fn flag_is_linewise(flag: &str) -> bool {
    let flag = flag.trim();
    if flag.contains("LINE") {
        true
    } else if flag.contains("CHAR") || flag.contains("BLOCK") {
        false
    } else {
        flag.contains('"')
    }
}

/// Parse the header line of Vim's native multi-line register block:
/// "a TAB LINE TAB 0".  The content lines follow, each starting with TAB.
fn parse_native_register_start(rest: &str) -> Option<(char, bool)> {
    let (name, rest) = split_first(rest)?;
    let (name, rest) = if name == '"' {
        let (name, rest) = split_first(rest)?;
        (name, rest)
    } else {
        (name, rest)
    };
    let rest = rest.strip_prefix('@').unwrap_or(rest);
    let rest = rest.strip_prefix('\t')?;
    let (kind, _width) = rest.split_once('\t').unwrap_or((rest, ""));
    if kind.is_empty() {
        return None;
    }
    Some((name, kind.contains("LINE")))
}

/// Turn a completed native register block into a register, restoring the
/// trailing newline of linewise text.
fn push_register_block(vi: &mut VimInfo, (name, linewise, lines): (char, bool, Vec<String>)) {
    let mut text = lines.join("\n");
    if linewise && !text.is_empty() {
        text.push('\n');
    }
    vi.registers.push(VimInfoRegister {
        name,
        text,
        linewise,
    });
}

/// Parse the part of a '!' line after the marker.
fn parse_global(rest: &str) -> Option<(String, String)> {
    let (name, value) = rest.split_once('\t')?;
    if name.is_empty() {
        return None;
    }
    // Vim writes "!name TAB {STR|NUM|FLO|DIC|LIS|BLO|XPL} TAB value"; accept
    // that type tag defensively, but do not treat a two-character value that
    // merely looks like one as a tag.
    let value = match value.split_once('\t') {
        Some((tag, value)) if is_global_type_tag(tag) => value,
        _ => value,
    };
    Some((unescape_str(name), unescape_str(value)))
}

/// The global-variable type tags Vim writes (write_viminfo_varlist()).
fn is_global_type_tag(tag: &str) -> bool {
    matches!(tag, "STR" | "NUM" | "FLO" | "DIC" | "LIS" | "BLO" | "XPL")
}

/// Parse the last-search-pattern line, accepting both "~/pat" and Vim's
/// "~msSle0~/pat" flag form.  A substitute pattern ('&') is not modelled.
fn parse_last_search(rest: &str) -> Option<String> {
    let index = rest.find(['/', '&'])?;
    if rest[index..].starts_with('&') {
        return None;
    }
    Some(unescape_str(&rest[index + 1..]))
}

/// Escape one value so that it survives on a single line.
fn escape_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || c == '\u{7f}' => {
                out.push_str(&format!("\\x{:02x}", c as u32));
            }
            c => out.push(c),
        }
    }
    out
}

/// Inverse of [escape_str]; also understands Vim's CTRL-V escapes.
fn unescape_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut chars = s.chars().peekable();
    while let Some(ch) = chars.next() {
        if ch == '\u{16}' {
            // CTRL-V: viminfo_writestring() writes CTRL-V + 'n' for newline and
            // CTRL-V + CTRL-V for a literal CTRL-V.
            match chars.next() {
                Some('n') => out.push('\n'),
                Some(c) => out.push(c),
                None => {}
            }
            continue;
        }
        if ch != '\\' {
            out.push(ch);
            continue;
        }
        match chars.next() {
            None => out.push('\\'),
            Some('\\') => out.push('\\'),
            Some('n') => out.push('\n'),
            Some('r') => out.push('\r'),
            Some('t') => out.push('\t'),
            Some('e') | Some('E') => out.push('\u{1b}'),
            Some('x') | Some('X') => {
                let mut value = 0u32;
                let mut digits = 0;
                while digits < 2 {
                    let Some(digit) = chars.peek().and_then(|c| c.to_digit(16)) else {
                        break;
                    };
                    value = value * 16 + digit;
                    chars.next();
                    digits += 1;
                }
                match (digits, char::from_u32(value)) {
                    (0, _) => out.push('x'),
                    (_, Some(c)) => out.push(c),
                    (_, None) => out.push('\u{fffd}'),
                }
            }
            Some(c) => {
                // Unknown escape: keep it verbatim so nothing is lost.
                out.push('\\');
                out.push(c);
            }
        }
    }
    out
}

/// A collision-free temporary file name in the same directory as path (renaming
/// across directories could fail on Windows or lose the atomicity).
fn temp_path(path: &Path) -> PathBuf {
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let sequence = COUNTER.fetch_add(1, Ordering::Relaxed);
    let pid = std::process::id();
    let name = path
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_else(|| String::from("viminfo"));
    let dir = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    dir.join(format!(".{name}.{pid}.{sequence}.tmp"))
}

