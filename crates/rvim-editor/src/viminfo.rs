    #[test]
    fn global_variables_round_trip_special_characters() {
        let mut vi = VimInfo::default();
        let value = String::from("tab\there\nnew line\r\\backslash\u{1}end");
        vi.globals.push(("WITH_SPECIALS".into(), value.clone()));
        let text = vi.format();
        let line = text
            .lines()
            .find(|line| line.starts_with("!WITH_SPECIALS\t"))
            .expect("global line");
        assert_eq!(
            line.matches('\t').count(),
            1,
            "value must be escaped: {line:?}"
        );
        assert!(line.contains("\\t"), "tab escape: {line:?}");
        assert!(line.contains("\\n"), "newline escape: {line:?}");
        assert!(line.contains("\\\\"), "backslash escape: {line:?}");
        assert_eq!(VimInfo::parse(&text).globals, vi.globals);
    }

