//! M8 compatibility closure: session/view files and the remaining small
//! `ex_docmd.c` commands (`:packadd`, `:behave`, `:legacy`, `:mode`,
//! `:open`, menu stubs).

use std::path::PathBuf;

use rvim_core::{VimError, VimResult};
use rvim_editor::Editor;
use rvim_viml::Env;

use crate::exec::ExOutcome;
use crate::parser::ParsedEx;
use crate::script::ScriptState;

fn default_name(name: &str) -> &'static str {
    match name {
        "mkview" => "View.vim",
        "mkvimrc" => "vimrc",
        _ => "Session.vim",
    }
}

fn escape_name(name: &str) -> String {
    name.replace('\\', "/").replace(' ', "\\ ")
}

/// `:mksession` / `:mkvimrc`: a small but sourceable session file.
pub fn cmd_session_write(ed: &mut Editor, p: &ParsedEx, name: &str) -> VimResult<ExOutcome> {
    let path = if p.args.trim().is_empty() {
        PathBuf::from(default_name(name))
    } else {
        PathBuf::from(p.args.trim())
    };
    let mut out = String::new();
    out.push_str("\" RustVim session (generated by :mksession)\n");
    out.push_str("set nocompatible\n");
    for buffer in ed.all_buffers() {
        let display = buffer.display_name();
        if display.is_empty() || display == "[No Name]" {
            continue;
        }
        let lnum = buffer.last_cursor.line + 1;
        out.push_str(&format!("badd +{} {}\n", lnum, escape_name(&display)));
    }
    let current = ed.current_buffer().display_name();
    if !current.is_empty() && current != "[No Name]" {
        out.push_str(&format!("edit {}\n", escape_name(&current)));
        out.push_str(&format!("normal! {}G\n", ed.cursor().line + 1));
    }
    std::fs::write(&path, out).map_err(|e| {
        VimError::new(
            "E482",
            format!("Can't write session file {}: {e}", path.display()),
        )
    })?;
    ed.messages
        .info(format!("Session file written: {}", path.display()));
    Ok(ExOutcome::Continue)
}

/// `:mkview`: record the cursor (and search pattern) for this buffer.
pub fn cmd_mkview(ed: &mut Editor, p: &ParsedEx) -> VimResult<ExOutcome> {
    let path = if p.args.trim().is_empty() {
        PathBuf::from(default_name("mkview"))
    } else {
        PathBuf::from(p.args.trim())
    };
    let cursor = ed.cursor();
    let current = ed.current_buffer().display_name();
    let mut out = String::new();
    out.push_str("\" RustVim view (generated by :mkview)\n");
    if !current.is_empty() && current != "[No Name]" {
        out.push_str(&format!("edit {}\n", escape_name(&current)));
    }
    out.push_str(&format!(
        "normal! {}G{}|\n",
        cursor.line + 1,
        cursor.col + 1
    ));
    if !ed.search_pattern.is_empty() {
        out.push_str(&format!(
            "let @/ = '{}'\n",
            ed.search_pattern.replace('\'', "''")
        ));
    }
    std::fs::write(&path, out).map_err(|e| {
        VimError::new(
            "E482",
            format!("Can't write view file {}: {e}", path.display()),
        )
    })?;
    ed.messages
        .info(format!("View file written: {}", path.display()));
    Ok(ExOutcome::Continue)
}

/// `:loadview`: source the view file through the normal script runner.
pub fn cmd_loadview(
    ed: &mut Editor,
    env: &mut Env,
    state: &mut ScriptState,
    p: &ParsedEx,
) -> VimResult<ExOutcome> {
    let path = if p.args.trim().is_empty() {
        PathBuf::from(default_name("mkview"))
    } else {
        PathBuf::from(p.args.trim())
    };
    crate::handlers_script::source_file(ed, env, state, &path)
}

/// `:sleep [N][m/s]`: wait while still delivering job/timer events.
pub fn cmd_sleep(
    ed: &mut Editor,
    env: &mut Env,
    state: &mut ScriptState,
    p: &ParsedEx,
) -> VimResult<ExOutcome> {
    let text = p.args.trim().to_ascii_lowercase();
    let (number, unit) = if let Some(number) = text.strip_suffix('m') {
        (number, 'm')
    } else if let Some(number) = text.strip_suffix('s') {
        (number, 's')
    } else {
        (text.as_str(), 's')
    };
    let amount: u64 = number.trim().parse().unwrap_or(1);
    let millis = if unit == 'm' { amount } else { amount * 1000 };
    let deadline = std::time::Instant::now() + std::time::Duration::from_millis(millis);
    while std::time::Instant::now() < deadline {
        crate::m7::pump(ed, env, state);
        std::thread::sleep(std::time::Duration::from_millis(10));
    }
    Ok(ExOutcome::Continue)
}

/// Commands RustVim accepts but does not need to act on (menus, mouse
/// behaviour, Vim9 legacy marker, pack loading in the headless build).
pub fn cmd_compat_noop(ed: &mut Editor, p: &ParsedEx, name: &str) -> VimResult<ExOutcome> {
    match name {
        "packadd" | "packloadall" => {
            let arg = if p.args.trim().is_empty() {
                "packages".to_string()
            } else {
                p.args.trim().to_string()
            };
            ed.messages
                .info(format!("packadd: no runtime package loaded ({arg})"));
        }
        "mode" => {
            ed.messages
                .info("mode: terminal mouse/mode settings are not modelled".to_string());
        }
        "behave" => {}
        "legacy" | "aunmenu" | "menutranslate" | "tlunmenu" => {}
        "open" => {
            if !p.args.trim().is_empty() {
                crate::exec::run_line(ed, &format!("edit {}", p.args.trim()))?;
            }
        }
        _ => {
            return Err(VimError::new(
                "ERV001",
                format!("compatibility command {name} has no handler"),
            ));
        }
    }
    Ok(ExOutcome::Continue)
}
