/// Dispatch a call; returns None when the name is not handled here.
pub fn call(name: &str, args: &[Value], env: &mut Env, host: &mut dyn Host) -> Option<ValueResult> {
    if !FUNCS.contains(&name) {
        return None;
    }
    Some((|| {
        check_arity(name, args)?;
        dispatch(name, args, env, host)
    })())
}

fn dispatch(name: &str, args: &[Value], env: &mut Env, host: &mut dyn Host) -> ValueResult {
    match name {
        // ------------------------------------------------------ numbers etc.
        "cosh" => Ok(Value::Float(arg(args, 0).to_float()?.cosh())),
        "cscope_connection" => Ok(Value::Number(0)),
        "debugbreak" => {
            let pid = narg(args, 0);
            if pid == 0 {
                return Err(err("E474", "Invalid argument"));
            }
            // Interrupting another process needs DebugBreakProcess() (Win32) or
            // a signal; neither is reachable from std, so report failure the
            // way Vim reports an unreachable process.
            Ok(Value::Number(-1))
        }
        "eventhandler" => Ok(Value::Number(0)),

        // ------------------------------------------------- strings / blobs
        "blob2list" => match arg(args, 0) {
            Value::Blob(blob) => Ok(Value::list(
                blob.borrow()
                    .iter()
                    .map(|&b| Value::Number(b as i64))
                    .collect(),
            )),
            _ => Err(err("E1238", "Blob required for argument 1")),
        },
        "byteidx" | "byteidxcomp" => {
            let text = string_arg(&arg(args, 0))?;
            let idx = narg(args, 1);
            let units = char_units(&text, name == "byteidxcomp");
            if idx < 0 || idx as usize > units.len() {
                return Ok(Value::Number(-1));
            }
            let offset = units.get(idx as usize).copied().unwrap_or(text.len());
            Ok(Value::Number(offset as i64))
        }
        "charidx" => {
            let text = string_arg(&arg(args, 0))?;
            let idx = narg(args, 1);
            let mut countcc = false;
            if args.len() > 2 {
                let flag = narg(args, 2);
                if flag != 0 && flag != 1 {
                    return Err(err("E1023", format!("Using a Number as a Bool: {flag}")));
                }
                countcc = flag == 1;
            }
            if idx < 0 || idx as usize >= text.len() {
                return Ok(Value::Number(-1));
            }
            let idx = idx as usize;
            let count = char_units(&text, countcc)
                .iter()
                .filter(|&&start| start <= idx)
                .count() as i64;
            Ok(Value::Number((count - 1).max(0)))
        }
        "charclass" => {
            let Value::String(text) = arg(args, 0) else {
                return Err(err("E1174", "String required for argument 1"));
            };
            let class = text.chars().next().map(char_class).unwrap_or(0);
            Ok(Value::Number(class))
        }

        // ------------------------------------------------------------ files
        "delete" => {
            let fname = string_arg(&arg(args, 0))?;
            let flags = if args.len() > 1 {
                string_arg(&arg(args, 1))?
            } else {
                String::new()
            };
            if fname.is_empty() {
                return Err(err("E474", "Invalid argument"));
            }
            let ok = match flags.as_str() {
                "" => std::fs::remove_file(&fname).is_ok(),
                "d" => std::fs::remove_dir(&fname).is_ok(),
                "rf" => std::fs::remove_dir_all(&fname).is_ok(),
                other => {
                    return Err(err("E15", format!("Invalid expression: \"{other}\"")));
                }
            };
            Ok(Value::Number(if ok { 0 } else { -1 }))
        }
        "chdir" => {
            let Some(Value::String(dir)) = args.first() else {
                // Not a String: Vim returns an empty string, no error.
                return Ok(Value::String(String::new()));
            };
            let previous = std::env::current_dir()
                .map(|p| p.display().to_string())
                .unwrap_or_default();
            let command = format!("cd {}", escape_filename(dir));
            match host.execute_command(&command, env) {
                Some(Ok(())) => Ok(Value::String(previous)),
                _ => Ok(Value::String(String::new())),
            }
        }
        "exepath" => {
            let name = string_arg(&arg(args, 0))?;
            let found = find_executable(&name).map(|p| p.display().to_string());
            Ok(Value::String(found.unwrap_or_default()))
        }
        "environ" => {
            let mut dict = VimDict::new();
            for (key, value) in std::env::vars_os() {
                if let (Ok(key), Ok(value)) = (key.into_string(), value.into_string()) {
                    dict.insert(key, Value::String(value));
                }
            }
            Ok(Value::dict(dict))
        }

        // ----------------------------------------------------------- misc
        "echoraw" => {
            // The output side effect needs the screen; the argument is still
            // evaluated by the caller (that is where Vim's errors come from).
            let _ = arg(args, 0);
            Ok(Value::Number(0))
        }
        "exists_compiled" => Err(err(
            "E1233",
            "exists_compiled() can only be used in a :def function",
        )),
        "byte2line" => byte2line(args, env, host),

        // -------------------------------------------------------- digraphs
        "digraph_get" => {
            let text = string_arg(&arg(args, 0))?;
            let bytes = text.as_bytes();
            if bytes.len() != 2 {
                return Err(err(
                    "E1214",
                    format!("Digraph must be just two characters: {text}"),
                ));
            }
            let code = digraph_get_code(bytes[0] as u32, bytes[1] as u32);
            let value = if code == 0 {
                String::new()
            } else {
                char::from_u32(code).map(String::from).unwrap_or_default()
            };
            Ok(Value::String(value))
        }
        "digraph_getlist" => {
            let list_all = args.first().map(|v| v.to_number() != 0).unwrap_or(false);
            let mut out = Vec::new();
            if list_all {
                for &(a, b, result) in DIGRAPH_DEFAULT {
                    let found = digraph_exact(a as u32, b as u32).unwrap_or(b as u32);
                    if found == result {
                        out.push(digraph_pair(a as u32, b as u32, result));
                    }
                }
            }
            USER_DIGRAPHS.with(|user| {
                for &(a, b, result) in user.borrow().iter() {
                    out.push(digraph_pair(a, b, result));
                }
            });
            Ok(Value::list(out))
        }
        "digraph_set" => {
            let chars = string_arg(&arg(args, 0))?;
            let digraph = string_arg(&arg(args, 1))?;
            register_digraph(&chars, &digraph)?;
            Ok(Value::Bool(true))
        }
        "digraph_setlist" => {
            let Value::List(items) = arg(args, 0) else {
                return Err(err("E1216", DIGRAPH_SETLIST_ERR));
            };
            let entries = items.borrow().clone();
            for item in entries {
                let Value::List(pair) = item else {
                    return Err(err("E1216", DIGRAPH_SETLIST_ERR));
                };
                let pair = pair.borrow().clone();
                if pair.len() != 2 {
                    return Err(err("E1216", DIGRAPH_SETLIST_ERR));
                }
                let chars = string_arg(&pair[0])?;
                let digraph = string_arg(&pair[1])?;
                register_digraph(&chars, &digraph)?;
            }
            Ok(Value::Bool(true))
        }

        // ---------------------------------------------------------- lists
        "extendnew" => extendnew(args),
        _ => Err(err("E117", format!("Unknown function: {name}"))),
    }
}

// ---------------------------------------------------------------------------
// helpers
