    /// Host that executes Ex command lines (used by `assert_fails`/`chdir`).
    struct ExecHost;
    impl Host for ExecHost {
        fn execute_command(
            &mut self,
            line: &str,
            _env: &mut Env,
        ) -> Option<rustvim_result_alias::Result<()>> {
            if line.starts_with("fail") {
                Some(Err(VimError::new(
                    "E492",
                    "Not an editor command: fail_command",
                )))
            } else {
                Some(Ok(()))
            }
        }
    }
    // Alias kept local so the signature above stays readable.
    mod rustvim_result_alias {
        pub type Result<T> = rvim_core::VimResult<T>;
    }

    /// Host with a small in-memory buffer for `byte2line()`.
    struct BufHost {
        lines: Vec<&'static str>,
        fileformat: &'static str,
    }
    impl Host for BufHost {
        fn option_get(&mut self, name: &str) -> Option<Value> {
            if name == "fileformat" {
                Some(Value::string(self.fileformat))
            } else {
                None
            }
        }

        fn call_host_builtin(
            &mut self,
            name: &str,
            args: Vec<Value>,
            _env: &mut Env,
        ) -> Option<ValueResult> {
            match name {
                "line" => Some(Ok(Value::Number(self.lines.len() as i64))),
                "getline" => {
                    let lnum = args[0].to_number();
                    let text = if lnum >= 1 {
                        self.lines.get(lnum as usize - 1).copied().unwrap_or("")
                    } else {
                        ""
                    };
                    Some(Ok(Value::string(text)))
                }
                _ => None,
            }
        }
    }

    fn run(name: &str, args: Vec<Value>) -> ValueResult {
        let mut env = Env::new();
        let mut host = H;
        call(name, &args, &mut env, &mut host).expect("implemented function")
    }

    fn temp_file(tag: &str, contents: &[u8]) -> std::path::PathBuf {
        let mut path = std::env::temp_dir();
        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0);
        path.push(format!("rvim_ae_{}_{}_{}", std::process::id(), tag, nanos));
        std::fs::write(&path, contents).expect("write temp file");
        path
    }

