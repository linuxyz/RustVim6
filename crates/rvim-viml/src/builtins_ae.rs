    fn t_blob2list() {
        let result = run("blob2list", vec![Value::blob(vec![1, 2, 255])]);
        let Value::List(list) = result.unwrap() else {
            panic!("expected list");
        };
        let values: Vec<i64> = list.borrow().iter().map(Value::to_number).collect();
        assert_eq!(values, vec![1, 2, 255]);
        let error = run("blob2list", vec![Value::Number(1)]).unwrap_err();
        assert_eq!(error.code, "E1238");
    }

