fn err(code: &'static str, msg: impl Into<String>) -> VimError {
    VimError::new(code, msg.into())
}

fn arg(args: &[Value], i: usize) -> Value {
    args.get(i).cloned().unwrap_or(Value::Null)
}

fn narg(args: &[Value], i: usize) -> i64 {
    arg(args, i).to_number()
}

fn string_arg(value: &Value) -> Result<String, VimError> {
    match value {
        Value::String(s) => Ok(s.clone()),
        Value::Number(_) | Value::Float(_) | Value::Bool(_) | Value::Null => {
            Ok(value.to_string_value())
        }
        Value::List(_) => Err(err("E730", "Using a List as a String")),
        Value::Dict(_) => Err(err("E731", "Using a Dictionary as a String")),
        Value::Funcref(_) => Err(err("E729", "Using a Funcref as a String")),
        Value::Blob(_) => Err(err("E976", "Using a Blob as a String")),
    }
}

/// Byte offsets where each Vim "character" starts.
///
/// With `countcc` every code point starts a new character; otherwise a
/// composing character is part of the preceding base character (Vim's
/// `utfc_ptr2len()` / `utf_ptr2len()` split in `byteidx()`).
fn char_units(text: &str, countcc: bool) -> Vec<usize> {
    let mut units = Vec::new();
    for (offset, c) in text.char_indices() {
        let composing = !countcc && interval_contains(COMBINING_RANGES, c as u32);
        if !composing || units.is_empty() {
            units.push(offset);
        }
    }
    units
}

/// Escape a file name for use in an Ex command line (`fnameescape()`-like).
fn escape_filename(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        if " \t\n*?[{`$\\%#'\"|!<".contains(c) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

