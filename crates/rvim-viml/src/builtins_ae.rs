thread_local! {
    /// User-defined digraphs, like Vim's `user_digraphs`.
    static USER_DIGRAPHS: RefCell<Vec<(u32, u32, u32)>> = const { RefCell::new(Vec::new()) };
}

fn register_digraph(chars: &str, digraph: &str) -> Result<(), VimError> {
    let pair: Vec<char> = chars.chars().collect();
    if pair.len() != 2 {
        return Err(err(
            "E1214",
            format!("Digraph must be just two characters: {chars}"),
        ));
    }
    if pair[0] == '\u{1b}' || pair[1] == '\u{1b}' {
        return Err(err("E104", "Escape not allowed in digraph"));
    }
    let result: Vec<char> = digraph.chars().collect();
    if result.len() != 1 {
        return Err(err(
            "E1215",
            format!("Digraph must be one character: {digraph}"),
        ));
    }
    let (c1, c2, code) = (pair[0] as u32, pair[1] as u32, result[0] as u32);
    USER_DIGRAPHS.with(|user| {
        let mut list = user.borrow_mut();
        if let Some(entry) = list.iter_mut().find(|(a, b, _)| *a == c1 && *b == c2) {
            entry.2 = code;
        } else {
            list.push((c1, c2, code));
        }
    });
    Ok(())
}

/// `getexactdigraph()`: user digraphs first, then the default table.
fn digraph_exact(c1: u32, c2: u32) -> Option<u32> {
    let user = USER_DIGRAPHS.with(|user| {
        user.borrow()
            .iter()
            .find(|(a, b, _)| *a == c1 && *b == c2)
            .map(|(_, _, result)| *result)
    });
    if let Some(result) = user {
        return Some(result);
    }
    DIGRAPH_DEFAULT
        .iter()
        .find(|(a, b, _)| *a as u32 == c1 && *b as u32 == c2)
        .map(|(_, _, result)| *result)
}

/// `digraph_get()`: the exact pair first, then the reversed pair.
fn digraph_get_code(c1: u32, c2: u32) -> u32 {
    let mut result = digraph_exact(c1, c2).unwrap_or(c2);
    if result == c2 && c1 != c2 {
        result = digraph_exact(c2, c1).unwrap_or(c1);
        if result == c1 {
            return 0;
        }
    }
    result
}

/// One `[chars, digraph]` entry for `digraph_getlist()`.
fn digraph_pair(c1: u32, c2: u32, result: u32) -> Value {
    let key: String = [c1 & 0xff, c2 & 0xff]
        .iter()
        .filter_map(|&b| char::from_u32(b))
        .collect();
    let value = char::from_u32(result).map(String::from).unwrap_or_default();
    Value::list(vec![Value::String(key), Value::String(value)])
}

