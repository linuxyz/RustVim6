/// Unicode character classes (0: blank, 1: punctuation, 2: word, 3: emoji;
/// otherwise the class number from the table).
fn char_class(c: char) -> i64 {
    let code = c as u32;
    if code < 0x100 {
        // Vim's quick check for Latin-1: ' ' '\t' NUL 0xa0 are blank, word
        // characters come from the default 'iskeyword' (@,48-57,_,192-255).
        if code == 0 || c == ' ' || c == '\t' || code == 0xa0 {
            return 0;
        }
        if c.is_ascii_alphanumeric() || c == '_' || code >= 192 {
            return 2;
        }
        return 1;
    }
    if interval_contains(EMOJI_RANGES, code) {
        return 3;
    }
    for &(first, last, class) in CHARCLASS_RANGES {
        if code < first {
            break;
        }
        if code <= last {
            return class as i64;
        }
    }
    // Most other characters are word characters.
    2
}

fn interval_contains(table: &[(u32, u32)], code: u32) -> bool {
    table
        .iter()
        .any(|&(first, last)| first <= code && code <= last)
}

