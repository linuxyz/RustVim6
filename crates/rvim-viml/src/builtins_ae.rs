    #[test]
    fn t_charidx() {
        // Bytes: a(0) combining-acute(1,2) b(3).
        let text = "a\u{301}b";
        assert_eq!(
            run("charidx", vec![Value::string(text), Value::Number(2)])
                .unwrap()
                .to_number(),
            0
        );
        // By default the composing character belongs to the base character.
        assert_eq!(
            run("charidx", vec![Value::string(text), Value::Number(3)])
                .unwrap()
                .to_number(),
            1
        );
        // With {countcc} every code point is counted.
        assert_eq!(
            run(
                "charidx",
                vec![Value::string(text), Value::Number(3), Value::Number(1)]
            )
            .unwrap()
            .to_number(),
            2
        );
        assert_eq!(
            run("charidx", vec![Value::string(text), Value::Number(100)])
                .unwrap()
                .to_number(),
            -1
        );
    }

