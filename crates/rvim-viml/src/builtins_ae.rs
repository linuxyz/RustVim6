fn extendnew(args: &[Value]) -> ValueResult {
    let target = arg(args, 0);
    let source = arg(args, 1);
    match (&target, &source) {
        (Value::List(left), Value::List(right)) => {
            let mut items = left.borrow().clone();
            let extra = right.borrow().clone();
            if args.len() > 2 {
                let before = narg(args, 2);
                let len = items.len() as i64;
                let at = if before < 0 { len + before } else { before };
                if at < 0 || at > len {
                    return Err(err("E684", format!("List index out of range: {before}")));
                }
                for (offset, item) in extra.into_iter().enumerate() {
                    items.insert(at as usize + offset, item);
                }
            } else {
                items.extend(extra);
            }
            Ok(Value::list(items))
        }
        (Value::Dict(left), Value::Dict(right)) => {
            let action = if args.len() > 2 {
                string_arg(&arg(args, 2))?
            } else {
                "force".to_string()
            };
            if !matches!(action.as_str(), "keep" | "force" | "error") {
                return Err(err("E474", format!("Invalid argument: {action}")));
            }
            let mut result = VimDict::new();
            for (key, value) in left.borrow().iter() {
                result.insert(key.clone(), value.clone());
            }
            let extra: Vec<(String, Value)> = right
                .borrow()
                .iter()
                .map(|(key, value)| (key.clone(), value.clone()))
                .collect();
            for (key, value) in extra {
                let exists = result.get(&key).is_some();
                match action.as_str() {
                    "keep" if exists => continue,
                    "error" if exists => {
                        return Err(err("E737", format!("Key already exists: {key}")));
                    }
                    _ => {}
                }
                result.insert(key, value);
            }
            Ok(Value::dict(result))
        }
        _ => Err(err(
            "E712",
            "Argument of extendnew() must be a List or Dictionary",
        )),
    }
}

