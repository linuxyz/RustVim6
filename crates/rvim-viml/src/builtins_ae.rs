// byte2line()
// ---------------------------------------------------------------------------

fn byte2line(args: &[Value], env: &mut Env, host: &mut dyn Host) -> ValueResult {
    let byte = narg(args, 0);
    if byte <= 0 {
        return Ok(Value::Number(-1));
    }
    let line_count = match host.call_host_builtin("line", vec![Value::string("$")], env) {
        Some(Ok(value)) => value.to_number(),
        _ => return Ok(Value::Number(-1)),
    };
    // Vim counts the end-of-line: one byte for "unix", two for "dos".
    let eol = match host.option_get("fileformat") {
        Some(Value::String(format)) if format == "dos" => 2,
        _ => 1,
    };
    let mut total = 0i64;
    for lnum in 1..=line_count {
        let Some(text) = host_line(env, host, lnum) else {
            return Ok(Value::Number(-1));
        };
        total += text.len() as i64 + eol;
        if byte <= total {
            return Ok(Value::Number(lnum));
        }
    }
    Ok(Value::Number(-1))
}

fn host_line(env: &mut Env, host: &mut dyn Host, lnum: i64) -> Option<String> {
    match host.call_host_builtin("getline", vec![Value::Number(lnum)], env) {
        Some(Ok(Value::String(text))) => Some(text),
        _ => None,
    }
}

