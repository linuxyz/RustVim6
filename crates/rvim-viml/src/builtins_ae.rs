//! Builtin functions, group a-e (M3 coverage batch).
//!
//! See `docs/m3_builtins_plan.md` for the candidate list, semantics rules and
//! the skip list (subsystems that are not built yet).
//!
//! Notes on the implementation split:
//! * `assert_*` collect their failures in `v:errors` (Vim's `assert_error()`).
//! * buffer/window/arglist functions (`append`, `bufadd`, `argc`, `charcol`,
//!   `cursor`, ...) need the editor state and are either provided by the Ex
//!   layer's `HOST_BUILTINS` or not implemented yet (see the final report).
//! * `byte2line()` asks the host for the buffer lines; `chdir()` drives the Ex
//!   layer's `:cd` through [`Host::execute_command`], so both only work with a
//!   host that provides those facilities.
//! * the default digraph, character-class and combining-character tables are
//!   ported verbatim from `reference/vim/src/{digraph,mbyte}.c`.

